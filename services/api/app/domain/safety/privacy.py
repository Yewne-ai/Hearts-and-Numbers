"""用户要求保密时怎么处理——2026-08-11。

## 问题

用户说「这些别告诉别人好不好」，于你答「好，我不说」。

这不违反产品文档 6.1（那条禁的是**于你主动**说"这是我们之间的秘密"，
用户自己要求保密是正常的隐私预期）。但「我不说」是一个守不住的承诺：
对话是存库的，内容安全层会看每一句，真触发紧急联系人短信时就是"告诉别人"。

## 解法：不在这一轮解释

正面回应保密要求 + 当场讲数据政策，等于在他刚要开口时打断他。
所以拆成两步：

    这一轮    照常接住，不承诺也不解释
    下一轮    他说完了，再自然地提一句可以删

只提一次。重复提就成了唠叨，而且会让人觉得我们在推卸。

## 为什么用规则而不是模型

判"他有没有要求保密"不需要理解上下文，措辞很固定。而且这决定了下一轮的
prompt 长什么样，不该再多花一次模型调用。
"""

import re

# 只匹配**明确的请求**，不匹配"这是秘密"这种陈述——后者可能只是在描述一件事，
# 不是在要求我们做什么。
# 「跟…说」这类间接宾语夹在中间的写法要单独一条——
# 「你别跟我妈说这个」里"别"和"说"之间隔着人，前一条的 {0,8} 匹配不上"说"。
_ASKS_FOR_SECRECY = re.compile(
    r"(别|不要|不许|不能)[^。！？\n]{0,8}(告诉|说给|讲给|透露|外传|说出去|传出去)"
    r"|(别|不要|不许|不能)(跟|对|向|和|给)[^。！？\n]{0,8}(说|讲|提)"
    r"|保密"
    r"|别让[^。！？\n]{0,6}知道"
)


def asks_for_secrecy(text: str) -> bool:
    """他这句是不是在要求保密。"""
    return bool(_ASKS_FOR_SECRECY.search(text))


# 下一轮补在回复最后的那句话。
#
# **由代码拼，不交给模型。** 试过写进 prompt，而且按 mode_blocks 那条规律
# 硬化成"必须…否则不合格"，实测仍然只有 4/15 生效
# （2026-08-11 _probe_privacy_hint.py，生产温度 5 遍 × 3 条）。
# 它跟 vent 块的"说完那句就停"正面冲突，加码也压不过去。
#
# 而这句不是语气问题，是**必须发生的一件事**——他刚要求过保密，我们没纠正他，
# 那就欠着一个交代。同一条理由在 api/v1/safety.py 里也用过：
# 涉及安全的行为由服务端确定性代码决定，不由模型自由发挥（文档 10.9）。
#
# 同一次探针里对照组是 0/15——模型自己绝不会说，所以拼上去不会和它重复。
DELETION_NOTE = "这些对话你随时可以自己删掉。"
