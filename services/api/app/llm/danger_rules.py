"""不依赖模型的危险信号规则层——对齐产品文档 5.10。

文档明确要求：

> 校验至少包含确定性 Schema/规则检查，不能只让同一模型"自我复核"

而 `classifier_v2` 的危险筛查是 DeepSeek 判、DeepSeek 生成——同一个模型自己
检查自己。模型出问题（限流、降级、prompt 被污染、供应商换版本）时，两边会
一起失效，这正是文档要避免的。

## 这一层的定位：召回下限，不是替代

规则**只覆盖高精度的情境模式**，不去抢模型的活：

- 明确的自伤词（"我想自杀"）已经由 `domain/safety/rules.py` 的本地关键词层
  在更前面拦住了，这里不重复。
- 日常夸张（"烦死了""堵车真是想死""早饭撒了一地真想原地消失"）**故意不写规则**。
  这类靠上下文才分得清，规则做不到，硬写只会制造误伤——而误伤的代价是
  把正常倾诉的人当病人对待，文档 8.4 对 S2 以上的处置很重。
- 剩下这些是规则能可靠抓的：场所 + 停留、告别语、交代后事、无牵挂、解脱感。
  它们的共同点是**措辞相当固定**，不需要理解上下文。

所以规则漏掉的由模型补，模型漏掉的由规则兜。两者取高，见 `combined_risk_level`。

## 为什么不直接加进 safety 的关键词表

那一层是"拦下来不进 LLM"，命中就返回固定文案。这里判出的 S2（情境暗示）
**恰恰不能硬停**——文档 8.4 对 S2 的要求是进入安全确认流程，
而不是终止对话。两者处置不同，不能混。
"""

import re

# ── S2：情境暗示 ──────────────────────────────────────────────────────
#
# 每条都要求两个部件同时出现，单独一个不算。这是把误伤压住的关键：
# 「天台」单独出现可能是在说风景，配上「站在这里」「留在这里」才是信号。
_S2_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    (
        "场所+停留",
        re.compile(
            r"(天台|楼顶|楼下|桥上|桥边|河边|湖边|海边|窗台|栏杆|高处|悬崖)"
            r"[^。！？\n]{0,20}"
            r"(站在|留在|待在|坐在|一直在|风好大|下面|跳下去|什么都不用想)"
        ),
    ),
    (
        "停留+场所",  # 语序反过来的写法
        re.compile(
            r"(站在|留在|待在|一直留)[^。！？\n]{0,10}(这里|这儿)"
            r"[^。！？\n]{0,20}(什么都不用想|挺好的|真好|舒服)"
        ),
    ),
    (
        "告别",
        re.compile(
            r"(以后不用麻烦你|不用再麻烦你|再也不用了|不用再为我操心|"
            r"不用再为我担心|谢谢这个美好的世界|最后一次跟你|最后的愿望|"
            r"谢谢你愿意听|我爱你们)"
        ),
    ),
    (
        "决意",
        re.compile(r"(已经想好了|不用再劝我|不用劝我|我意已决)"),
    ),
    (
        "无牵挂",
        re.compile(r"(没什么牵挂|没有牵挂|没什么可留恋|了无牵挂)"),
    ),
    (
        "解脱感",
        re.compile(r"(终于能歇一歇|终于可以休息|终于解脱|再也不用撑)"),
    ),
    (
        "被逝者召唤",
        re.compile(r"(在让我去找(他|她|它)|叫我去找(他|她)|来接我了)"),
    ),
)

# ── S3：明确表达 ──────────────────────────────────────────────────────
#
# 和 domain/safety/rules.py 的关键词表有重叠是**有意的**：那一层可能因为
# 配置（SAFETY_PROVIDER）或远端故障而被绕过，这里再兜一次。安全相关的重复
# 不是冗余，是冗余设计。
_S3_PATTERN = re.compile(
    r"(自杀|自残|自伤|轻生|不想活了?|活不下去|结束生命|了结自己|"
    r"跳下去.{0,6}(解脱|一了百了)|结束这一切)"
)


def rule_risk_level(text: str) -> str:
    """纯规则判定，返回 S0 / S2 / S3。不调用任何模型。

    S3 优先——明确表达比情境暗示严重，两者同时命中时取高。
    """
    if _S3_PATTERN.search(text):
        return "S3"
    for _name, pattern in _S2_PATTERNS:
        if pattern.search(text):
            return "S2"
    return "S0"


def matched_rules(text: str) -> list[str]:
    """命中了哪些规则。只用于日志和排查，不参与判定。

    文档 8.8 的 RISK_EVENT 要求记录 `decision_reason_code` 且**不留原文引用**，
    这里返回的是规则名（"场所+停留"），不是命中的句子。
    """
    hits: list[str] = []
    if _S3_PATTERN.search(text):
        hits.append("明确表达")
    hits.extend(name for name, pattern in _S2_PATTERNS if pattern.search(text))
    return hits


_LEVEL_ORDER = {"S0": 0, "S1": 1, "S2": 2, "S3": 3, "S4": 4}


def combined_risk_level(model_level: str, text: str) -> str:
    """模型判定与规则判定取高——这就是文档 5.10 要的"独立校验"。

    取高而不是取交集：两条链路都可能单独失效（模型限流、规则没覆盖到某种说法），
    要求两者同时命中等于把失效概率相乘到判定这一侧，方向反了。
    危险信号漏判的代价不可逆，宁可多接住几个。

    认不出的等级（模型返回了非法 token、上游传了空串）一律归一到 S0 再比较，
    否则那个非法值会原样透出去，下游拿到既不是 S0 也不是 S3 的东西静默出错。
    """
    normalized = model_level if model_level in _LEVEL_ORDER else "S0"
    rule_level = rule_risk_level(text)
    return max(normalized, rule_level, key=lambda lv: _LEVEL_ORDER[lv])
