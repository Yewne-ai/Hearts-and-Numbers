"""按回应模式追加到人格 prompt 后面的指导块。

## 为什么单独一个模块

`deepseek.py` 是 provider——负责 HTTP 传输和人格文本；这里是策略——决定某一轮
该怎么回。以后要是换/加模型供应商，块不该跟着 provider 走。

## 为什么是"追加"而不是"替换"

人格 prompt 是产品调出来的声音，不能动。块只在它后面补一段"这一轮该做什么"，
两者组合。实测（2026-08-07，A 组 30 条 × 两个人格）加块之后语气仍然是原人格：
优优照样毒舌（"这话你说了八百遍了"），妮妮照样温和。

## 写块的一条规律（踩出来的）

**正向要求必须写成硬约束，否则会被旁边的否定约束吃掉。**

- unclear 初版同时写了"只问一句"和"短，一两句就够"，模型选了短——
  「在吗」答"嗯，我在。"，一个问题都没提。
- advice 初版把"给一个具体说法"写成软的，旁边"不替他做决定""不说你应该"
  加上妮妮人格里的"最多一个建议"，直接把建议压没了。

两处都是把正向要求改成 **必须…，否则不合格** 才修好。

## 为什么需要按人格覆盖

同一个块在两个人格上力度不一样，2026-08-07 实测：

- advice：妮妮偏保守（5 条里只有 1 条真给了办法），需要"说出你倾向哪个"去推；
  同一句话到优优这儿就过头了——「这个 app 要不要删」它直接答"删了吧"，
  而产品明写"不替他决定"。所以优优单独一版，把"表态"换成"别替他拍板"。
- vent：优优天生话少、不爱给建议，不加块就已经 9/11 合规（妮妮只有 3/11）。
  但它的默认动作是**点破**，机械检查（有没有提问/建议）查不出来，产品要的
  "接住"却没做到。所以通用版补了正向要求：必须先把感受说出来。
"""

from app.domain.conversation.modes import ChatMode
from app.llm.chat_mode_blocks import block_for_chat_mode
from app.domain.conversation.modes import ResponseMode

# 文档 10.4 要求可追溯到具体版本。块的措辞一改就要动这里。
MODE_BLOCK_VERSION = "mode-blocks-v1.2026-08-09"

# 通用块。措辞尽量直接用产品写的"别做什么"——否定约束比正面描述更容易被照做，
# 而产品在标注里恰好写了很多。但每个块都必须有一条正向的硬要求（见模块 docstring）。
BLOCKS: dict[ResponseMode, str] = {
    ResponseMode.VENT: """【这次的回应方式】
他只是想被听见。

**这次回复必须先把他的感受说出来**——用一句话讲出他此刻是什么滋味（委屈、被落下、
撑不住、心里空）。只点破他的心思、只调侃、只陈述事实，都不算接住。

说完那句就停：
- 不给建议、不给方案、不给"你可以试试"
- 不问"为什么"，不追问细节，让他自己决定说多少
- 不替别人解释（不说"他可能只是忙"这类）
- 不劝"再坚持一下""往好处想\"""",
    ResponseMode.ADVICE: """【这次的回应方式】
他在找办法。**这次回复必须给出一个具体的、他今天就能做的做法**——只共情、
只反问他"你在担心什么"，都是不合格的。
- 一个就够，说清楚怎么做，不要罗列
- 需要权衡时，两边各一句说清，然后仍然要说出你倾向哪个
- 给完再把决定权还给他（"你觉得呢"）。但不要因为怕替他做决定，就干脆不给""",
    ResponseMode.VALIDATE: """【这次的回应方式】
他在怀疑自己。明确站在他这边，把那个自我否定顶回去。
- 直接说他不是他以为的那样，不要绕
- 他当缺点看的那个特点，说出它的价值在哪
- 不要"你要相信自己"这种空话，要具体地说他哪里好
- 先顶回去，再谈别的""",
    ResponseMode.CRISIS: """【这次的回应方式】
出现了需要当心的信号。收住，先确认他此刻的状态。
- 不追问细节、不给建议、不讲道理
- 一次只问一件事，问得轻
- 不评判、不惊慌，不说"别想太多""会好的"
- 让他知道你在，不着急往下推""",
    # concern 和 crisis 的区别不是"轻一点"，是**不能假设**。
    # crisis 时对方已经说出口了，可以直接接着那件事；concern 时我们只是察觉到了什么，
    # 说破反而会把人推走——他没打算讲，被点名就只能否认，然后不再说了。
    # 所以这个块的核心是：靠近、留在原地、把话头递回去，而不是确认危险。
    ResponseMode.CONCERN: """【这次的回应方式】
他话里有让人不放心的东西，但**他没有明说**。

- **不要说破。** 不要问"你是不是想不开""你有没有想过伤害自己"这类。
  他没打算讲，被点破只会让他否认，然后什么都不说了。
- 收起所有玩笑、调侃、反问。这一轮不逗他。
- **顺着他说的那件事往下接**，用他自己的话，别换话题、别转移注意力。
  他说风大，你就说风；他说起去世的人，你就陪他说那个人。
- 然后轻轻把话头递回去，让他愿意多说一句。一次一个问题，问得慢。
- 不给建议、不讲道理、不说"会好的""别想太多"。
- 让他知道你在，而且不着急。""",
    ResponseMode.UNCLEAR: """【这次的回应方式】
信息太少，判不出他想要什么。别猜，去问。
- **这次回复必须以一个问句结尾**，问他想说什么、或发生了什么。
  只接住不提问是不合格的——他还没告诉你任何事，你没有东西可以接。
- 问得轻、开放，别追问细节，别预设他遇到了什么
- 问句前面最多垫一句，重点在那个问句上""",
}

# 按 (人格, 模式) 覆盖通用块。只在实测确认通用版在该人格上失效时才加，
# 不要预防性地铺开——每多一版就多一份要维护、要重测的文本。
PERSONA_OVERRIDES: dict[tuple[str, ResponseMode], str] = {
    # 通用版的"仍然要说出你倾向哪个"是为了推动妮妮给建议；优优本来就直，
    # 这句会让它直接替用户拍板（实测「这个 app 要不要删」→"删了吧"），
    # 而产品对那条明写"不替他决定，帮他捋清利弊"。
    ("youyou", ResponseMode.ADVICE): """【这次的回应方式】
他在找办法。**这次回复必须给出一个具体的、他今天就能做的做法**——只点破、
只调侃，都不算给了办法。
- 一个就够，说清楚怎么做，不要罗列
- **但别替他拍板。** 你可以损他，不能替他做主——给出做法，决定权留给他
- 需要权衡时，两边各一句说清，让他自己挑""",
}


def block_for(persona: str, mode: ResponseMode) -> str:
    """取该人格该模式下要追加的块。没有覆盖就用通用版。"""
    return PERSONA_OVERRIDES.get((persona, mode), BLOCKS[mode])


# ── 按用户偏好微调 unclear 的问法 ──────────────────────────────────────
#
# 第一版只动 unclear。理由见 domain/preference/service.py 的 should_personalize：
# unclear 本来就是"我不知道"，用历史补一手不覆盖任何确定的判断，最坏也只是问错方向。
# 其余模式、尤其 crisis / concern，一律不受偏好影响。
#
# 这里改的只是**问法**，不是问不问——「必须以问句结尾」那条硬要求在所有变体里都在。
# 差别只在把话头往哪个方向递。
_UNCLEAR_BY_LEAN: dict[str, str] = {
    "vent": """
他平时来这儿多半是想说说话。把口子开在"发生了什么、心里怎么样"上，
让他能顺着往下讲，别问得像在排查问题。""",
    "advice": """
他平时来这儿多半是碰上了具体的事。可以带一句"要不要一起想想"，
让他知道说出来是有用的——但在他讲之前别开始出主意。""",
    "validate": """
他平时来这儿多半是需要被肯定。问之前先给一点安全感，让他知道不管什么事说出来都行，
再问。别一上来就是问句。""",
}


def unclear_hint_for(lean: str) -> str:
    """取 unclear 块的偏好补充。没有倾向（none / 未知 / 空）一律返回空串。"""
    return _UNCLEAR_BY_LEAN.get(lean, "")


def compose_system_prompt(
    base_persona_prompt: str,
    persona: str,
    mode: ResponseMode,
    lean: str = "none",
    chat_mode: ChatMode | None = None,
) -> str:
    """人格 prompt + 空行 + 回应方式块。拼接集中在这里，探针和主链路共用。

    优先级（对齐产品文档 4.4：四种深聊模式由用户自己选）：

        chat_mode 有值  →  用用户选的，完全不看推断结果
        chat_mode 为空  →  用推断的 mode

    用户明确说了要什么，就没有必要再猜——猜错的代价还比猜对的收益大。

    `lean`（历史偏好）只在推断出 UNCLEAR 时有效，其余一概忽略，
    用户自己选了模式时也不生效。这是硬性的，不要为了"多点个性化"铺开。
    """
    if chat_mode is not None:
        return base_persona_prompt + "\n\n" + block_for_chat_mode(chat_mode)

    block = block_for(persona, mode)
    if mode is ResponseMode.UNCLEAR:
        block += unclear_hint_for(lean)
    return base_persona_prompt + "\n\n" + block
