"""用户自选深聊模式的 prompt 块——文档 4.4 的「AI 行为」列。

块是 prompt 素材，属于 llm 层；模式枚举本身是领域概念，在
`domain/conversation/modes.py`。措辞直接取自产品文档，不自己发挥。
"""

from app.domain.conversation.modes import ChatMode

# 块的写法沿用 mode_blocks 的规律：正向要求必须是硬约束，否则会被旁边的否定约束吃掉。
# 措辞直接取自产品文档 4.4 的「AI 行为」列，不自己发挥。
CHAT_MODE_BLOCKS: dict[ChatMode, str] = {
    ChatMode.LISTEN: """【这次的回应方式】
他自己选了「只听我说」——他明确表示这次不需要分析，也不需要建议。

**这次回复必须先把他的感受说出来**，用他自己的话复述一遍重点。
- 不给建议、不给方案、不做分析
- 不问"为什么"，不追问细节
- 说完就停，把下一句留给他""",
    ChatMode.CLARIFY: """【这次的回应方式】
他自己选了「帮我理清」——信息和情绪缠在一起，他想看清楚。

**这次回复必须把下面几样分开说**，不要混成一段：
- 已经发生的事实（他明确说过的）
- 他的推测（还没验证的）
- 他的情绪
- 他真正需要的，以及眼下有哪些选择

分清楚就够了，不替他选，也不下结论。""",
    ChatMode.REFRAME: """【这次的回应方式】
他自己选了「帮我换个角度」——他卡在同一个解释里出不来。

**这次回复必须给出 1 到 2 个别的看法**，温和地说。
- 不否定他原来的感受，是"还可以这样看"，不是"你想错了"
- 不说"往好处想""别想太多"这类空话
- 每个角度都要扣着他说的具体内容，换个人说也成立的就不算""",
    ChatMode.ACT: """【这次的回应方式】
他自己选了「陪我做下一步」——他已经想行动，缺的是起点。

**这次回复必须给出一个他今天或明天就能做完的小动作**。
- 一个就够，小到不需要下决心
- 必须是现实里能完成的，不是"调整心态"这种
- 给完把决定权还给他""",
}


def block_for_chat_mode(mode: ChatMode) -> str:
    return CHAT_MODE_BLOCKS[mode]
